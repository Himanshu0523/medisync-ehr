import { useState } from 'react';
import { Link } from 'react-router-dom';
import AuthLayout from '../../components/auth/AuthLayout';

export default function MfaVerificationPage() {
  const [code, setCode] = useState(['', '', '', '', '', '']);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleChange = (index, value) => {
    if (!/^[0-9]?$/.test(value)) return;
    const newCode = [...code];
    newCode[index] = value;
    setCode(newCode);

    // Auto-focus next input
    if (value && index < 5) {
      const nextInput = document.getElementById(`mfa-digit-${index + 1}`);
      if (nextInput) nextInput.focus();
    }
  };

  const handleKeyDown = (index, e) => {
    if (e.key === 'Backspace' && !code[index] && index > 0) {
      const prevInput = document.getElementById(`mfa-digit-${index - 1}`);
      if (prevInput) prevInput.focus();
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    const fullCode = code.join('');
    if (fullCode.length !== 6) {
      setError('Please enter all 6 digits of your authenticator code.');
      return;
    }

    setLoading(true);
    setError('');
    // Simulates MFA validation; backend integration hook
    setTimeout(() => {
      setLoading(false);
      setError('Multi-Factor Authentication module is being staged by system administration.');
    }, 800);
  };

  return (
    <AuthLayout
      title="Two-Factor Authentication"
      subtitle="Enter the 6-digit security code generated by your mobile authenticator app."
      showHero={false}
      maxWidth="max-w-md"
    >
      <form onSubmit={handleSubmit} className="space-y-5">
        {error && (
          <div className="p-3.5 rounded-xl bg-amber-50 border border-amber-200 text-amber-800 text-xs animate-fade-in">
            {error}
          </div>
        )}

        <div className="flex justify-center gap-2 sm:gap-3 py-2">
          {code.map((digit, idx) => (
            <input
              key={idx}
              id={`mfa-digit-${idx}`}
              type="text"
              inputMode="numeric"
              maxLength={1}
              value={digit}
              onChange={(e) => handleChange(idx, e.target.value)}
              onKeyDown={(e) => handleKeyDown(idx, e)}
              className="w-11 h-13 text-center text-xl font-bold rounded-xl border border-slate-200 bg-slate-50/50 text-slate-900 focus:outline-none focus:ring-2 focus:ring-blue-600 focus:bg-white transition"
            />
          ))}
        </div>

        <button
          type="submit"
          disabled={loading}
          className="w-full py-3.5 px-4 rounded-xl font-bold bg-blue-600 hover:bg-blue-700 text-white transition shadow-lg shadow-blue-500/25 flex items-center justify-center gap-2 text-sm disabled:opacity-60 cursor-pointer"
        >
          {loading ? (
            <>
              <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
              <span>Verifying Token...</span>
            </>
          ) : (
            <span>Verify Security Code</span>
          )}
        </button>

        <div className="pt-2 text-center text-xs text-slate-500 space-y-2">
          <p>
            Didn&apos;t receive a code?{' '}
            <button type="button" className="font-bold text-blue-600 hover:underline">
              Use Emergency Backup Code
            </button>
          </p>
          <p>
            <Link to="/login" className="font-semibold text-slate-400 hover:text-slate-600">
              Return to Sign In
            </Link>
          </p>
        </div>
      </form>
    </AuthLayout>
  );
}
